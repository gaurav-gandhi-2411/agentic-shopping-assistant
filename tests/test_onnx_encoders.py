"""Unit tests for the ONNX encoders. No torch, no real weights: tiny committed ONNX graphs
(tests/fixtures/onnx_tiny, regenerated by make_fixture.py) plus a toy tokenizer built in-test.
"""
from __future__ import annotations

import shutil
from pathlib import Path

import numpy as np
import pytest
from PIL import Image
from tokenizers import Tokenizer, models, pre_tokenizers, processors

from src.retrieval import onnx_encoders as oe

FIX = Path(__file__).parent / "fixtures" / "onnx_tiny"
WORDS = ["[PAD]", "[UNK]", "[CLS]", "[SEP]", "red", "dress", "blue", "shirt", "long", "kurta"]


def _toy_tokenizer(path: Path, cls: str = "[CLS]", sep: str = "[SEP]") -> None:
    vocab = {w: i for i, w in enumerate(WORDS)}
    tok = Tokenizer(models.WordLevel(vocab, unk_token="[UNK]"))
    tok.pre_tokenizer = pre_tokenizers.Whitespace()
    tok.post_processor = processors.TemplateProcessing(
        single=f"{cls} $A {sep}", special_tokens=[(cls, vocab[cls]), (sep, vocab[sep])]
    )
    tok.save(str(path))


@pytest.fixture()
def model_root(tmp_path: Path) -> Path:
    """ONNX_MODEL_DIR-shaped dir: <root>/all-MiniLM-L6-v2 and <root>/clip-ViT-B-32."""
    mini = tmp_path / "all-MiniLM-L6-v2"
    mini.mkdir()
    shutil.copy(FIX / "text_model.onnx", mini / "model.onnx")
    _toy_tokenizer(mini / "tokenizer.json")
    clip = tmp_path / "clip-ViT-B-32"
    clip.mkdir()
    shutil.copy(FIX / "clip_text.onnx", clip / "text.onnx")
    shutil.copy(FIX / "clip_vision.onnx", clip / "vision.onnx")
    _toy_tokenizer(clip / "tokenizer.json", cls="[CLS]", sep="[SEP]")
    return tmp_path


@pytest.fixture()
def tables() -> dict[str, np.ndarray]:
    return dict(np.load(FIX / "tables.npz"))


def _ids(*words: str) -> list[int]:
    return [2, *(WORDS.index(w) for w in words), 3]


def test_encoder_backend_default_and_validation(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.delenv("ENCODER_BACKEND", raising=False)
    assert oe.encoder_backend() == "onnx"
    monkeypatch.setenv("ENCODER_BACKEND", "Torch")
    assert oe.encoder_backend() == "torch"
    monkeypatch.setenv("ENCODER_BACKEND", "tensorrt")
    with pytest.raises(ValueError, match="ENCODER_BACKEND"):
        oe.encoder_backend()


def test_model_dir_uses_last_segment_and_env(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    monkeypatch.setenv("ONNX_MODEL_DIR", str(tmp_path))
    assert oe.onnx_model_dir("sentence-transformers/all-MiniLM-L6-v2") == (
        tmp_path / "all-MiniLM-L6-v2"
    )
    assert oe.onnx_model_dir("clip-ViT-B-32", root=tmp_path / "x") == tmp_path / "x" / "clip-ViT-B-32"


def test_text_encoder_mean_pools_over_attention_mask(
    model_root: Path, tables: dict[str, np.ndarray]
) -> None:
    enc = oe.OnnxTextEncoder("sentence-transformers/all-MiniLM-L6-v2", root=model_root)
    vecs = enc.encode(["red dress", "blue shirt long kurta"], normalize_embeddings=False)
    assert vecs.shape == (2, 4) and vecs.dtype == np.float32
    # expected: mean of the table rows of [CLS] tokens [SEP], pad rows excluded
    for got, ids in zip(vecs, [_ids("red", "dress"), _ids("blue", "shirt", "long", "kurta")]):
        np.testing.assert_allclose(got, tables["text"][ids].mean(axis=0), atol=1e-6)


def test_text_encoder_normalises_and_is_batch_invariant(model_root: Path) -> None:
    enc = oe.OnnxTextEncoder("all-MiniLM-L6-v2", root=model_root)
    texts = ["red dress", "blue shirt long kurta", "kurta"]
    batch = enc.encode(texts, batch_size=2, normalize_embeddings=True)
    np.testing.assert_allclose(np.linalg.norm(batch, axis=1), 1.0, atol=1e-6)
    for i, t in enumerate(texts):  # padding must not change a vector
        np.testing.assert_allclose(enc.encode([t], normalize_embeddings=True)[0], batch[i], atol=1e-6)


def test_text_encoder_single_string_empty_list_and_unknown_words(model_root: Path) -> None:
    enc = oe.OnnxTextEncoder("all-MiniLM-L6-v2", root=model_root)
    assert enc.encode("red dress", normalize_embeddings=True).shape == (4,)
    assert enc.encode([], normalize_embeddings=True).shape == (0, 4)
    # hostile input: unknown tokens map to [UNK]; empty string is just [CLS] [SEP]
    assert np.isfinite(enc.encode(["zzz qqq", ""], normalize_embeddings=True)).all()


def test_text_encoder_truncates_at_max_seq_length(model_root: Path) -> None:
    enc = oe.OnnxTextEncoder("all-MiniLM-L6-v2", root=model_root)
    enc.max_seq_length = 256
    long_text = " ".join(["red"] * 300)
    # 300 words truncate to 256 tokens (incl. specials): the vector is the mean of [CLS] + 254 red + [SEP]
    got = enc.encode([long_text], normalize_embeddings=False)[0]
    tab = np.load(FIX / "tables.npz")["text"]
    ids = [2] + [4] * 254 + [3]
    np.testing.assert_allclose(got, tab[ids].mean(axis=0), atol=1e-5)


def test_missing_model_files_raise_runtime_error_with_hint(tmp_path: Path) -> None:
    with pytest.raises(RuntimeError, match="export_onnx"):
        oe.OnnxTextEncoder("all-MiniLM-L6-v2", root=tmp_path)
    with pytest.raises(RuntimeError, match="Failed to load CLIP model"):
        oe.OnnxCLIPEncoder("clip-ViT-B-32", root=tmp_path)


def test_clip_text_unit_norm_and_matches_numpy(model_root: Path, tables: dict[str, np.ndarray]) -> None:
    enc = oe.OnnxCLIPEncoder("clip-ViT-B-32", root=model_root)
    vecs = enc.encode_texts(["red dress", "blue shirt"])
    assert vecs.shape == (2, 4) and vecs.dtype == np.float32
    np.testing.assert_allclose(np.linalg.norm(vecs, axis=1), 1.0, atol=1e-6)
    exp = tables["clip"][_ids("red", "dress")].mean(axis=0)
    np.testing.assert_allclose(vecs[0], exp / np.linalg.norm(exp), atol=1e-6)


def test_clip_text_batches_over_64(model_root: Path) -> None:
    enc = oe.OnnxCLIPEncoder("clip-ViT-B-32", root=model_root)
    texts = ["red dress", "blue shirt long kurta"] * 40  # 80 > the 64 batch size
    vecs = enc.encode_texts(texts)
    assert vecs.shape == (80, 4)
    np.testing.assert_allclose(vecs[0], vecs[2], atol=1e-6)


def test_preprocess_matches_clip_recipe() -> None:
    # solid colour: resize/crop are no-ops on values, so the result is the normalised constant
    img = Image.new("RGB", (300, 150), color=(255, 0, 128))
    out = oe.preprocess_clip_image(img)
    assert out.shape == (3, 224, 224) and out.dtype == np.float32
    expect = (np.array([255, 0, 128], dtype=np.float32) / 255 - oe.CLIP_MEAN) / oe.CLIP_STD
    np.testing.assert_allclose(out[:, 0, 0], expect, atol=1e-5)
    np.testing.assert_allclose(out[:, 223, 223], expect, atol=1e-5)


def test_preprocess_centre_crops_long_side_and_handles_modes() -> None:
    # left half black, right half white, wide image: the centre crop must straddle the boundary
    arr = np.zeros((100, 400, 3), dtype=np.uint8)
    arr[:, 200:] = 255
    out = oe.preprocess_clip_image(Image.fromarray(arr))
    left, right = out[0, 112, 0], out[0, 112, 223]
    assert left < -1.0 < 1.0 < right
    # non-RGB modes (palette, RGBA, greyscale) are converted, never raise
    for mode in ("L", "RGBA", "P"):
        assert oe.preprocess_clip_image(Image.new(mode, (50, 80))).shape == (3, 224, 224)


def test_clip_image_encoder_unit_norm(model_root: Path) -> None:
    enc = oe.OnnxCLIPEncoder("clip-ViT-B-32", root=model_root)
    vec = enc.encode_image(Image.new("RGB", (64, 48), color=(200, 30, 90)))
    assert vec.shape == (3,) and vec.dtype == np.float32
    assert abs(float(np.linalg.norm(vec)) - 1.0) < 1e-6


